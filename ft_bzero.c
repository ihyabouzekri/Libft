#include "libft.h"

void	ft_bzero(void	*p, size_t	n)
{
	size_t	i;
	char	*ptr;

	i = 0;
	ptr = (char *)p;
	while (i < n)
	{
		ptr[i] = '\0';
		i++;
	}
}
